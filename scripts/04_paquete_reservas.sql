-- SECCION 1: Tabla de liquidacion mensual

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE liquidacion_mensual PURGE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;  -- -942: la tabla no existe
END;
/

CREATE TABLE liquidacion_mensual (
  id_liquidacion        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  anio                  NUMBER(4)    NOT NULL,
  mes                   NUMBER(2)    NOT NULL,
  id_alojamiento        NUMBER       NOT NULL,
  reservas_completadas  NUMBER       NOT NULL,
  ingreso_estadias      NUMBER(14,2) NOT NULL,
  ingreso_servicios     NUMBER(14,2) NOT NULL,
  total_liquidado       NUMBER(14,2) NOT NULL,
  fecha_proceso         DATE         DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_liquidacion PRIMARY KEY (id_liquidacion),
  CONSTRAINT uq_liquidacion UNIQUE (anio, mes, id_alojamiento),
  CONSTRAINT ck_liq_mes     CHECK (mes BETWEEN 1 AND 12),
  CONSTRAINT ck_liq_valores CHECK (reservas_completadas >= 0
                                   AND ingreso_estadias >= 0
                                   AND ingreso_servicios >= 0
                                   AND total_liquidado = ingreso_estadias + ingreso_servicios),
  CONSTRAINT fk_liq_alojamiento FOREIGN KEY (id_alojamiento)
             REFERENCES alojamiento (id_alojamiento)
);

COMMENT ON TABLE liquidacion_mensual IS 'Liquidacion mensual por alojamiento: una fila por alojamiento, año y mes, calculada por pkg_reservas.sp_liquidacion_mensual.';
COMMENT ON COLUMN liquidacion_mensual.reservas_completadas IS 'Reservas COMPLETADAS cuyo check-in cae dentro del mes liquidado.';
COMMENT ON COLUMN liquidacion_mensual.ingreso_estadias IS 'Suma de valor_estadia de las lineas de habitacion de esas reservas.';
COMMENT ON COLUMN liquidacion_mensual.ingreso_servicios IS 'Suma de cantidad * precio_unitario de los servicios de esas reservas.';


