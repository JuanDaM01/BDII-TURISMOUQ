-- SECCION 3: Cuerpo del paquete

CREATE OR REPLACE PACKAGE BODY pkg_reservas AS

  -- fn_valor_estadia: suma la tarifa de la temporada de cada noche de la estadia
  FUNCTION fn_valor_estadia (
    p_id_habitacion IN NUMBER,
    p_fecha_in      IN DATE,
    p_fecha_out     IN DATE
  ) RETURN NUMBER IS
    v_in     DATE := TRUNC(p_fecha_in);
    v_out    DATE := TRUNC(p_fecha_out);
    v_noche  DATE;
    v_valor  tarifa.valor_noche%TYPE;
    v_total  NUMBER := 0;
  BEGIN
    IF v_out <= v_in THEN
      RAISE_APPLICATION_ERROR(-20001, 'El check-out debe ser posterior al check-in.');
    END IF;

    -- las noches van de check-in a check-out menos un dia
    FOR i IN 0 .. (v_out - v_in - 1) LOOP
      v_noche := v_in + i;
      BEGIN
        SELECT ta.valor_noche
          INTO v_valor
          FROM temporada t
          JOIN tarifa ta ON ta.id_temporada = t.id_temporada
         WHERE ta.id_habitacion = p_id_habitacion
           AND v_noche BETWEEN t.fecha_inicio AND t.fecha_fin;
      EXCEPTION
        WHEN NO_DATA_FOUND THEN
          RAISE_APPLICATION_ERROR(-20007,
            'No hay tarifa vigente para la habitación ' || p_id_habitacion ||
            ' la noche del ' || TO_CHAR(v_noche, 'YYYY-MM-DD') || '.');
      END;
      v_total := v_total + v_valor;
    END LOOP;

    RETURN v_total;
  END fn_valor_estadia;


  -- sp_crear_reserva: valida y registra la cabecera y la linea de habitacion
  PROCEDURE sp_crear_reserva (
    p_id_cliente    IN  NUMBER,
    p_id_habitacion IN  NUMBER,
    p_check_in      IN  DATE,
    p_check_out     IN  DATE,
    p_huespedes     IN  NUMBER,
    p_id_reserva    OUT NUMBER
  ) IS
    v_in         DATE := TRUNC(p_check_in);
    v_out        DATE := TRUNC(p_check_out);
    v_id_aloj    habitacion.id_alojamiento%TYPE;
    v_capacidad  habitacion.capacidad%TYPE;
    v_existe     NUMBER;
    v_ocupada    NUMBER;
    v_valor      NUMBER;
  BEGIN
    -- 1. Fechas
    IF v_out <= v_in THEN
      RAISE_APPLICATION_ERROR(-20001, 'El check-out debe ser posterior al check-in.');
    END IF;
    IF v_in < TRUNC(SYSDATE) THEN
      RAISE_APPLICATION_ERROR(-20006, 'No se puede reservar con un check-in anterior a hoy.');
    END IF;

    -- 2. Cliente
    SELECT COUNT(*) INTO v_existe FROM cliente WHERE id_cliente = p_id_cliente;
    IF v_existe = 0 THEN
      RAISE_APPLICATION_ERROR(-20005, 'El cliente ' || p_id_cliente || ' no existe.');
    END IF;

    -- 3. Habitacion: de ella salen el alojamiento y la capacidad
    BEGIN
      SELECT id_alojamiento, capacidad
        INTO v_id_aloj, v_capacidad
        FROM habitacion
       WHERE id_habitacion = p_id_habitacion;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20004, 'La habitación ' || p_id_habitacion || ' no existe.');
    END;

    -- 4. Capacidad
    IF p_huespedes IS NULL OR p_huespedes < 1 OR p_huespedes > v_capacidad THEN
      RAISE_APPLICATION_ERROR(-20003,
        'Capacidad excedida o huéspedes inválidos: se pidieron ' || NVL(TO_CHAR(p_huespedes), 'NULL') ||
        ' y la habitación admite como máximo ' || v_capacidad || '.');
    END IF;

    -- 5. Disponibilidad: dos rangos se cruzan si cada uno empieza antes de que termine el otro
    SELECT COUNT(*)
      INTO v_ocupada
      FROM reserva_habitacion rh
      JOIN reserva r ON r.id_reserva = rh.id_reserva
     WHERE rh.id_habitacion = p_id_habitacion
       AND r.estado <> 'CANCELADA'
       AND rh.check_in  < v_out
       AND rh.check_out > v_in;
    IF v_ocupada > 0 THEN
      RAISE_APPLICATION_ERROR(-20002,
        'Habitación no disponible: la habitación ' || p_id_habitacion ||
        ' ya está reservada en alguna noche entre ' || TO_CHAR(v_in, 'YYYY-MM-DD') ||
        ' y ' || TO_CHAR(v_out, 'YYYY-MM-DD') || '.');
    END IF;

    -- 6. Registro (el valor se calcula antes para no dejar una cabecera sin linea si falta una tarifa)
    v_valor := fn_valor_estadia(p_id_habitacion, v_in, v_out);

    INSERT INTO reserva (id_cliente, id_alojamiento, fecha_reserva, check_in, check_out, estado)
    VALUES (p_id_cliente, v_id_aloj, TRUNC(SYSDATE), v_in, v_out, 'PENDIENTE')
    RETURNING id_reserva INTO p_id_reserva;

    INSERT INTO reserva_habitacion (id_reserva, id_habitacion, id_alojamiento,
                                    check_in, check_out, huespedes, valor_estadia)
    VALUES (p_id_reserva, p_id_habitacion, v_id_aloj, v_in, v_out, p_huespedes, v_valor);
  END sp_crear_reserva;


  -- sp_liquidacion_mensual: recorre los alojamientos con un cursor parametrizado por rango de fechas.
  -- La reserva cuenta en el mes de su check-in y solo si esta COMPLETADA.
  PROCEDURE sp_liquidacion_mensual (
    p_anio IN NUMBER,
    p_mes  IN NUMBER
  ) IS
    v_ini        DATE;
    v_fin        DATE;
    v_procesados NUMBER := 0;
    v_reservas   NUMBER := 0;
    v_total      NUMBER := 0;

    CURSOR c_liquidacion (cp_ini DATE, cp_fin DATE) IS
      SELECT a.id_alojamiento,
             a.nombre_comercial,
             (SELECT COUNT(*)
                FROM reserva r
               WHERE r.id_alojamiento = a.id_alojamiento
                 AND r.estado = 'COMPLETADA'
                 AND r.check_in >= cp_ini AND r.check_in < cp_fin) AS reservas,
             (SELECT NVL(SUM(rh.valor_estadia), 0)
                FROM reserva_habitacion rh
                JOIN reserva r ON r.id_reserva = rh.id_reserva
               WHERE r.id_alojamiento = a.id_alojamiento
                 AND r.estado = 'COMPLETADA'
                 AND r.check_in >= cp_ini AND r.check_in < cp_fin) AS ingreso_estadias,
             (SELECT NVL(SUM(rs.cantidad * rs.precio_unitario), 0)
                FROM reserva_servicio rs
                JOIN reserva r ON r.id_reserva = rs.id_reserva
               WHERE r.id_alojamiento = a.id_alojamiento
                 AND r.estado = 'COMPLETADA'
                 AND r.check_in >= cp_ini AND r.check_in < cp_fin) AS ingreso_servicios
        FROM alojamiento a
       ORDER BY a.id_alojamiento;

    v_fila c_liquidacion%ROWTYPE;
  BEGIN
    IF p_anio IS NULL OR p_mes IS NULL OR p_mes NOT BETWEEN 1 AND 12 OR p_anio < 2000 THEN
      RAISE_APPLICATION_ERROR(-20008, 'Año o mes inválido para la liquidación.');
    END IF;

    v_ini := TO_DATE(p_anio || '-' || LPAD(p_mes, 2, '0') || '-01', 'YYYY-MM-DD');
    v_fin := ADD_MONTHS(v_ini, 1);

    -- si el mes ya se habia liquidado se reemplaza
    DELETE FROM liquidacion_mensual WHERE anio = p_anio AND mes = p_mes;

    OPEN c_liquidacion(v_ini, v_fin);
    LOOP
      FETCH c_liquidacion INTO v_fila;
      EXIT WHEN c_liquidacion%NOTFOUND;

      INSERT INTO liquidacion_mensual (anio, mes, id_alojamiento, reservas_completadas,
                                       ingreso_estadias, ingreso_servicios, total_liquidado)
      VALUES (p_anio, p_mes, v_fila.id_alojamiento, v_fila.reservas,
              v_fila.ingreso_estadias, v_fila.ingreso_servicios,
              v_fila.ingreso_estadias + v_fila.ingreso_servicios);

      v_procesados := v_procesados + 1;
      v_reservas   := v_reservas + v_fila.reservas;
      v_total      := v_total + v_fila.ingreso_estadias + v_fila.ingreso_servicios;
    END LOOP;
    CLOSE c_liquidacion;

    DBMS_OUTPUT.PUT_LINE('Liquidación ' || p_anio || '-' || LPAD(p_mes, 2, '0') || ': ' ||
                         v_procesados || ' alojamientos, ' || v_reservas ||
                         ' reservas completadas, total liquidado ' || TO_CHAR(v_total));
  END sp_liquidacion_mensual;

END pkg_reservas;
/


