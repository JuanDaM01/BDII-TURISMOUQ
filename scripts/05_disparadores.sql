-- SECCION 1: Tabla de auditoria de tarifas
-- Sin llaves foraneas para que una tarifa borrada siga apareciendo en la auditoria

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE tarifa_auditoria PURGE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;  -- -942: la tabla no existe
END;
/

CREATE TABLE tarifa_auditoria (
  id_auditoria    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fecha_cambio    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  usuario         VARCHAR2(128) NOT NULL,
  operacion       VARCHAR2(10)  NOT NULL,
  id_tarifa       NUMBER        NOT NULL,
  id_habitacion   NUMBER        NOT NULL,
  id_temporada    NUMBER        NOT NULL,
  valor_anterior  NUMBER(10,2),
  valor_nuevo     NUMBER(10,2),
  CONSTRAINT pk_tarifa_auditoria PRIMARY KEY (id_auditoria),
  CONSTRAINT ck_tar_aud_operacion CHECK (operacion IN ('INSERT','UPDATE','DELETE'))
);

COMMENT ON TABLE tarifa_auditoria IS 'Bitacora de cambios sobre TARIFA: quien, cuando, operacion, valor anterior y valor nuevo.';
COMMENT ON COLUMN tarifa_auditoria.usuario IS 'Usuario de base de datos que ejecuto la sentencia.';
COMMENT ON COLUMN tarifa_auditoria.valor_anterior IS 'valor_noche antes del cambio; nulo en un INSERT.';
COMMENT ON COLUMN tarifa_auditoria.valor_nuevo IS 'valor_noche despues del cambio; nulo en un DELETE.';


-- SECCION 2: Disparador de sentencia, auditoria de TARIFA
-- Es compuesto porque un disparador de sentencia solo no ve :OLD ni :NEW.
-- Las filas se guardan en memoria y se insertan al terminar la sentencia.

CREATE OR REPLACE TRIGGER trg_tarifa_auditoria
  FOR INSERT OR UPDATE OR DELETE ON tarifa
  COMPOUND TRIGGER

  TYPE t_cambio IS RECORD (
    operacion       VARCHAR2(10),
    id_tarifa       NUMBER,
    id_habitacion   NUMBER,
    id_temporada    NUMBER,
    valor_anterior  NUMBER(10,2),
    valor_nuevo     NUMBER(10,2)
  );
  TYPE t_cambios IS TABLE OF t_cambio INDEX BY PLS_INTEGER;

  g_cambios  t_cambios;
  g_usuario  VARCHAR2(128);
  g_fecha    TIMESTAMP;

  BEFORE STATEMENT IS
  BEGIN
    g_usuario := SYS_CONTEXT('USERENV', 'SESSION_USER');
    g_fecha   := SYSTIMESTAMP;
  END BEFORE STATEMENT;

  AFTER EACH ROW IS
    v_c t_cambio;
  BEGIN
    IF INSERTING THEN
      v_c.operacion := 'INSERT';
    ELSIF UPDATING THEN
      v_c.operacion := 'UPDATE';
    ELSE
      v_c.operacion := 'DELETE';
    END IF;
    v_c.id_tarifa      := NVL(:NEW.id_tarifa, :OLD.id_tarifa);
    v_c.id_habitacion  := NVL(:NEW.id_habitacion, :OLD.id_habitacion);
    v_c.id_temporada   := NVL(:NEW.id_temporada, :OLD.id_temporada);
    v_c.valor_anterior := :OLD.valor_noche;
    v_c.valor_nuevo    := :NEW.valor_noche;
    g_cambios(g_cambios.COUNT + 1) := v_c;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
    v_c t_cambio;
  BEGIN
    FOR i IN 1 .. g_cambios.COUNT LOOP
      v_c := g_cambios(i);
      INSERT INTO tarifa_auditoria (fecha_cambio, usuario, operacion, id_tarifa,
                                    id_habitacion, id_temporada, valor_anterior, valor_nuevo)
      VALUES (g_fecha, g_usuario, v_c.operacion, v_c.id_tarifa,
              v_c.id_habitacion, v_c.id_temporada, v_c.valor_anterior, v_c.valor_nuevo);
    END LOOP;
  END AFTER STATEMENT;

END trg_tarifa_auditoria;
/


-- SECCION 3: Disparador de fila, solape de reservas
-- Una habitacion no puede tener dos lineas de reservas no canceladas con noches en comun.
-- Es compuesto porque un disparador de fila no puede consultar su propia tabla (ORA-04091):
-- las filas se recogen y la revision se hace al terminar la sentencia.

CREATE OR REPLACE TRIGGER trg_resha_solape
  FOR INSERT OR UPDATE OF id_habitacion, check_in, check_out, id_reserva
  ON reserva_habitacion
  COMPOUND TRIGGER

  TYPE t_linea IS RECORD (
    id_reserva_habitacion  NUMBER,
    id_reserva             NUMBER,
    id_habitacion          NUMBER,
    check_in               DATE,
    check_out              DATE
  );
  TYPE t_lineas IS TABLE OF t_linea INDEX BY PLS_INTEGER;

  g_lineas t_lineas;

  AFTER EACH ROW IS
    v_l t_linea;
  BEGIN
    v_l.id_reserva_habitacion := :NEW.id_reserva_habitacion;
    v_l.id_reserva            := :NEW.id_reserva;
    v_l.id_habitacion         := :NEW.id_habitacion;
    v_l.check_in              := :NEW.check_in;
    v_l.check_out             := :NEW.check_out;
    g_lineas(g_lineas.COUNT + 1) := v_l;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
    v_l       t_linea;
    v_choques NUMBER;
  BEGIN
    FOR i IN 1 .. g_lineas.COUNT LOOP
      v_l := g_lineas(i);

      -- dos rangos se cruzan si cada uno empieza antes de que termine el otro,
      -- por eso una reserva que empieza el dia en que otra termina es valida
      SELECT COUNT(*)
        INTO v_choques
        FROM reserva_habitacion o
        JOIN reserva ro ON ro.id_reserva = o.id_reserva
       WHERE o.id_habitacion = v_l.id_habitacion
         AND o.id_reserva_habitacion <> v_l.id_reserva_habitacion
         AND ro.estado <> 'CANCELADA'
         AND o.check_in  < v_l.check_out
         AND o.check_out > v_l.check_in
         AND EXISTS (SELECT 1
                       FROM reserva rn
                      WHERE rn.id_reserva = v_l.id_reserva
                        AND rn.estado <> 'CANCELADA');

      IF v_choques > 0 THEN
        RAISE_APPLICATION_ERROR(-20010,
          'Solape de reservas: la habitación ' || v_l.id_habitacion ||
          ' ya está ocupada en alguna noche entre ' || TO_CHAR(v_l.check_in, 'YYYY-MM-DD') ||
          ' y ' || TO_CHAR(v_l.check_out, 'YYYY-MM-DD') || '.');
      END IF;
    END LOOP;
  END AFTER STATEMENT;

END trg_resha_solape;
/


-- SECCION 4: Verificacion

-- los dos disparadores deben aparecer ENABLED
